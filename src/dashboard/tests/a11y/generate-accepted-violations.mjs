/**
 * generate-accepted-violations.mjs — pure markdown generator for the accepted-accessibility-
 * violations ledger.
 *
 * Phase 165 / A11Y-01, A11Y-03 / 165-CONTEXT.md D-05, D-06, D-07
 *
 * Mirrors `quirk/cli/errors_cmd.py::_dump_markdown()` — the same triad this repo already
 * CI-gates for `quirk errors --dump-md` -> `docs/error-codes.md` ->
 * `tests/test_error_codes_freshness.py`. This module performs NO filesystem I/O, prints
 * nothing, and never exits the process: it is a pure function of its arguments. I/O belongs to
 * the callers — `run-a11y.mjs` writes the generated string to
 * `src/dashboard/tests/a11y/ACCEPTED-VIOLATIONS.md`, and
 * `accepted-violations-freshness.test.ts` calls this function in-process to byte-compare
 * against the committed file.
 *
 * D-07: `impact` and the WCAG criterion are properties of the *rule*, not the node, so each is
 * recorded once per (route, rule) pair. Every entry carries `count`, which is what makes the
 * grand total mechanically reconstructible from the ledger alone.
 */

const DEFAULT_VARIANT = 'default'

/**
 * Escapes markdown-table-hostile characters in an evidence sample so a raw HTML snippet does
 * not break the table it is rendered inside. Pipes are escaped (table cell delimiter) and the
 * snippet is wrapped in an inline code span so angle brackets render literally instead of being
 * interpreted as markup by a markdown viewer.
 */
function fenceSample(html) {
  const escaped = String(html).replace(/\|/g, '\\|').replace(/`/g, "'")
  return `\`${escaped}\``
}

function renderWcag(wcag) {
  return Array.isArray(wcag) && wcag.length > 0 ? wcag.join(', ') : '—'
}

function renderJustification(justification) {
  const trimmed = typeof justification === 'string' ? justification.trim() : ''
  return trimmed.length > 0 ? trimmed : '**MISSING**'
}

/**
 * Normalizes the `baselinesByRoute` input (an array of `{ route, entries }` objects, or a Map
 * keyed by route) into a flat, sorted array of `{ route, ...entry }` rows so the rest of the
 * generator can iterate a single deterministic sequence regardless of input order or shape.
 */
function flattenAndSort(baselinesByRoute) {
  const routeEntries = Array.isArray(baselinesByRoute)
    ? baselinesByRoute
    : [...baselinesByRoute.entries()].map(([route, entries]) => ({ route, entries }))

  const rows = []
  for (const { route, entries } of routeEntries) {
    for (const entry of entries ?? []) {
      rows.push({ route, ...entry })
    }
  }

  rows.sort((a, b) => {
    if (a.route !== b.route) return a.route < b.route ? -1 : 1
    return a.rule < b.rule ? -1 : a.rule > b.rule ? 1 : 0
  })

  return rows
}

/**
 * Pure markdown generator. `baselinesByRoute` is an array of `{ route, entries }` objects (or
 * an equivalent Map), where each `entries` array holds the D-01 per-(route, rule) baseline
 * entry shape produced by `buildBaselineEntries` (`rule`, `count`, `impact`, `wcag`, `helpUrl`,
 * `justification`, `samples`).
 *
 * `variant` defaults to `"default"` (D-05/D-07: only the default variant's baselines feed the
 * main ledger unless a variant is passed explicitly) and is recorded in the banner so a
 * variant-scoped ledger is self-describing.
 */
export function generateMarkdown(baselinesByRoute, variant = DEFAULT_VARIANT) {
  const rows = flattenAndSort(baselinesByRoute)

  const routeCount = new Set(rows.map(r => r.route)).size
  const entryCount = rows.length
  const totalCount = rows.reduce((sum, r) => sum + (typeof r.count === 'number' ? r.count : 0), 0)

  const lines = [
    '# QU.I.R.K. Dashboard Accepted Accessibility Violations',
    '',
    '_Generated by `generate-accepted-violations.mjs` via `npm run a11y:baseline`. Do not edit by hand._',
    '',
    `Variant: \`${variant}\``,
    '',
    'D-07: impact and WCAG criterion are properties of the *rule*, not the node, so each is',
    'recorded once per (route, rule) pair below. Each row carries a `count`, which is what makes',
    'the grand total below mechanically reconstructible from this ledger alone.',
    '',
    `Totals: ${routeCount} route(s), ${entryCount} (route, rule) entries, ${totalCount} accepted violation node(s).`,
  ]

  let currentRoute = null
  for (const row of rows) {
    if (row.route !== currentRoute) {
      lines.push('')
      lines.push(`## ${row.route}`)
      lines.push('')
      lines.push('| Rule | Count | Impact | WCAG | Justification |')
      lines.push('|------|-------|--------|------|---------------|')
      currentRoute = row.route
    }
    lines.push(
      `| ${row.rule} | ${row.count} | ${row.impact} | ${renderWcag(row.wcag)} | ${renderJustification(row.justification)} |`,
    )
    const samples = Array.isArray(row.samples) ? row.samples.filter(Boolean) : []
    if (samples.length > 0) {
      lines.push('')
      lines.push(`<details><summary>${row.rule} evidence samples (${samples.length})</summary>`)
      lines.push('')
      for (const sample of samples) {
        lines.push(`- ${fenceSample(sample)}`)
      }
      lines.push('')
      lines.push('</details>')
    }
  }

  lines.push('') // trailing newline
  return lines.join('\n')
}
