#!/usr/bin/env python3
"""Generate the dashboard BrandLogo React component from the committed brand SVGs.

WHY THIS IS SEPARATE FROM THE OTHER BRAND GENERATORS
----------------------------------------------------
docs/brand/build_logo.py writes to whatever output directory it is given (the
drift gate calls it with tmp_path), so it cannot own a file inside the dashboard
source tree. scripts/build_brand_rasters.py needs the dev-only resvg renderer;
this component must regenerate without it, so it is stdlib only.

The transform (Phase 223 D-03/D-04/D-05):
- Ink (the dark brand colour) is rewritten to currentColor so the logo follows
  the theme foreground.
- The Signal accent colour is kept as a fixed fill (BRAND-GUIDELINES section 5);
  it is the logo's single error point and is never a UI token.
- <title>, <desc> and aria-labelledby are dropped; the accessible name is set
  once with aria-label so it is not read twice.
- The clip-path id is derived from React useId() so two mounted instances never
  produce a duplicate id (Pitfall 4).
- Hyphenated SVG attributes are remapped to their JSX camelCase names.

Determinism: no timestamp, no absolute path, LF line endings only, and a single
trailing newline, so tests/test_brand_assets_freshness.py can byte-compare it.

Regenerate with: python3 -m scripts.build_brand_component
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = REPO_ROOT / "src/dashboard/src/components/BrandLogo.tsx"
REGEN_COMMAND = "python3 -m scripts.build_brand_component"

INK = "#0D0124"
SIGNAL = "#7FE001"

# Light, transparent variants only: the -dark files carry an Ink tile (D-07).
SOURCES = {
    "logo": "docs/brand/quirk-logo.svg",
    "glyph": "docs/brand/quirk-favicon.svg",
}

ATTR_MAP = {
    "stroke-width": "strokeWidth",
    "stroke-linejoin": "strokeLinejoin",
    "stroke-miterlimit": "strokeMiterlimit",
    "stroke-linecap": "strokeLinecap",
    "clip-path": "clipPath",
}

_BAD_ATTR_RE = re.compile(r' (?!aria-|data-)[a-z]+-[a-z-]+="')
_VIEWBOX_RE = re.compile(r'viewBox="([^"]+)"')
_CLIP_ID_RE = re.compile(r'id="cap[0-9.]+"')
_CLIP_REF_RE = re.compile(r'clipPath="url\(#cap[0-9.]+\)"')


def body(svg_text: str) -> tuple[str, list[str]]:
    """Return (viewBox, JSX body lines) for one source SVG."""
    lines = svg_text.splitlines()
    m = _VIEWBOX_RE.search(lines[0])
    if not m:
        raise ValueError("source SVG has no viewBox on its first line")
    out: list[str] = []
    for raw in lines[3:-1]:
        line = raw.strip()
        if not line:
            continue
        line = line.replace(INK, "currentColor")
        for k, v in ATTR_MAP.items():
            line = line.replace(f' {k}="', f' {v}="')
        line = _CLIP_ID_RE.sub("id={clipId}", line)
        line = _CLIP_REF_RE.sub("clipPath={`url(#${clipId})`}", line)
        if INK in line or "<title" in line or "<desc" in line or _BAD_ATTR_RE.search(line):
            raise ValueError(f"unexpected construct after transform: {line[:100]}")
        out.append(line)
    return m.group(1), out


def _svg_block(variant: str, view_box: str, lines: list[str], indent: str) -> list[str]:
    head = (
        f'{indent}<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" '
        f'role="img" aria-label="QU.I.R.K." data-brand-variant="{variant}" className={{className}}>'
    )
    return [head, *[f"{indent}  {ln}" for ln in lines], f"{indent}</svg>"]


def render(sources: dict[str, str] | None = None) -> str:
    """Return the full BrandLogo.tsx text. sources maps 'logo'/'glyph' to SVG text."""
    if sources is None:
        sources = {
            k: (REPO_ROOT / p).read_text(encoding="utf-8") for k, p in SOURCES.items()
        }
    g_vb, g_lines = body(sources["glyph"])
    l_vb, l_lines = body(sources["logo"])
    out = [
        "// GENERATED by scripts/build_brand_component.py from docs/brand/quirk-logo.svg and",
        f"// docs/brand/quirk-favicon.svg. Do not hand-edit. Regenerate: {REGEN_COMMAND}",
        'import { useId } from "react"',
        "",
        'type Props = { variant?: "logo" | "glyph"; className?: string }',
        "",
        'export function BrandLogo({ variant = "logo", className }: Props) {',
        '  const clipId = `quirk-cap-${useId().replace(/[^A-Za-z0-9_-]/g, "")}`',
        '  if (variant === "glyph") {',
        "    return (",
        *_svg_block("glyph", g_vb, g_lines, "      "),
        "    )",
        "  }",
        "  return (",
        *_svg_block("logo", l_vb, l_lines, "    "),
        "  )",
        "}",
    ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT_PATH.read_bytes().decode("utf-8") if OUTPUT_PATH.exists() else None
        if current != text:
            print(f"{OUTPUT_PATH} is stale. Regenerate with: {REGEN_COMMAND}", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
